let ActiveLocale: Locale = 'es';
/** Synchronize the translation helper with the active UI preference. */
export function getActiveLocale(): Locale { return ActiveLocale; }
export function setActiveLocale(locale: Locale): void {
    ActiveLocale = locale;
}
/** Translate display strings while preserving leading and trailing whitespace. */
export function t<Value>(value: Value): Value {
    if (ActiveLocale !== 'en' || typeof value !== 'string')
        return value;
    const leading = value.match(/^\s*/)?.[0] ?? '';
    const trailing = value.match(/\s*$/)?.[0] ?? '';
    const trimmed = value.trim();
    if (!trimmed)
        return value;
    const translated = EnglishTranslations[trimmed];
    if (translated)
        return `${leading}${translated}${trailing}` as unknown as Value;
    return translateInterpolated(value) as unknown as Value;
}
/** Translate a small set of interpolated labels rendered by the dashboard. */
function translateInterpolated(value: string): string {
    const patterns: Array<[
        RegExp,
        string
    ]> = [
            [/^(\d+) comisiones registradas$/, '$1 registered groups'],
            [/^(\d+) materias registradas$/, '$1 registered subjects'],
            [/^(\d+) comisiones organizadas$/, '$1 organized groups'],
            [/^(\d+) clases en el sistema$/, '$1 classes in the system'],
            [/^(\d+) registros visibles$/, '$1 visible records'],
            [/^Bienvenido a tu espacio de trabajo, ([^.]+)\. Este es un entorno interactivo con información ficticia\.$/, 'Welcome to your workspace, $1. This is an interactive environment with fictional data.'],
            [/^Asistencia de (.+)$/, 'Attendance for $1'],
            [/^Nota de (.+)$/, 'Grade for $1'],
            [/^Editar (.+)$/, 'Edit $1'],
            [/^(.+) · Cuota anterior · (.+)$/, '$1 · Previous fee · $2'],
            [/^(.+) · Cuota actual · (.+)$/, '$1 · Current fee · $2'],
            [/^(\d+) registros disponibles para tu perfil$/, '$1 records available for your role'],
            [/^(\d+) alumnos inscriptos$/, '$1 enrolled students'],
            [/^(\d+) comisiones$/, '$1 groups'],
            [/^(\d+) alumnos$/, '$1 students'],
            [/^(\d+) resultados$/, '$1 results'],
            [/^(\d+) inscripciones$/, '$1 enrollments'],
            [/^(\d+) cuotas$/, '$1 fees'],
            [/^Registrado el (.+)\. El historial de inscripciones se conserva al desactivar un alumno\.$/, 'Registered on $1. Enrollment history is preserved when a student is deactivated.'],
            [/^Cuota anterior · (.+)$/, 'Previous fee · $1'],
            [/^Cuota actual · (.+)$/, 'Current fee · $1'],
        ];
    for (const [pattern, replacement] of patterns) {
        if (pattern.test(value))
            return value.replace(pattern, replacement);
    }
    return value;
}
